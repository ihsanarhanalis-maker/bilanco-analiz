function getLang(){ return _lang==='en'?'en':'tr'; }

function t(key, fallback){
  const pack=I18N[getLang()]||I18N.tr;
  if(pack[key]!=null) return pack[key];
  if(I18N.tr[key]!=null) return I18N.tr[key];
  return fallback!=null?fallback:key;
}

function applyI18n(){
  if(typeof document==='undefined') return;
  const lang=getLang();
  document.documentElement.lang=lang==='en'?'en':'tr';
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key=el.getAttribute('data-i18n');
    if(!key) return;
    /* nested i18n/id nodes: use data-i18n-html on the wrapper instead */
    if(el.children.length && el.querySelector('[data-i18n],[data-i18n-html],[id]')) return;
    el.textContent=t(key);
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el=>{
    const key=el.getAttribute('data-i18n-html');
    if(key) el.innerHTML=t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el=>{
    const key=el.getAttribute('data-i18n-placeholder');
    if(key) el.setAttribute('placeholder', t(key));
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el=>{
    const key=el.getAttribute('data-i18n-title');
    if(key) el.setAttribute('title', t(key));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el=>{
    const key=el.getAttribute('data-i18n-aria');
    if(key) el.setAttribute('aria-label', t(key));
  });
  const btn=document.getElementById('langBtn');
  if(btn){
    btn.textContent=lang==='en'?t('lang_to_tr'):t('lang_to_en');
    btn.setAttribute('title', lang==='en'?t('lang_title_tr'):t('lang_title_en'));
    btn.setAttribute('aria-label', lang==='en'?t('lang_title_tr'):t('lang_title_en'));
  }
  /* curNote may be recreated inside input_sub html */
  const cur=document.getElementById('curNote');
  if(cur && (!cur.textContent || /para biriminde|currency/i.test(cur.textContent))){
    cur.textContent=t('cur_in');
  }
  if(typeof document.title==='string'){
    document.title=lang==='en'?'Balance Sheet Analysis Tool':'Bilanço Analiz Aracı';
  }
  try{ window.dispatchEvent(new CustomEvent('bilanco-lang',{detail:{lang}})); }catch(_e){}
}

function setLang(lang){
  _lang=(lang==='en')?'en':'tr';
  try{ localStorage.setItem(LANG_KEY, _lang); }catch(_e){}
  applyI18n();
}

function toggleLang(){
  setLang(getLang()==='en'?'tr':'en');
}

function initLang(){
  let saved='tr';
  try{ saved=localStorage.getItem(LANG_KEY)||'tr'; }catch(_e){}
  _lang=(saved==='en')?'en':'tr';
  applyI18n();
  const btn=document.getElementById('langBtn');
  if(btn && !btn._langBound){
    btn._langBound=true;
    btn.addEventListener('click', toggleLang);
  }
}

function voiceSpeechLang(){
  return getLang()==='en'?'en-US':'tr-TR';
}

